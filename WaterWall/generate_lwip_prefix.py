#!/usr/bin/env python3
"""Writes the header that renames WaterWall's lwIP to srpww_*.

SSTP links its own lwIP, so WaterWall's copy must not bind to (or override) the same names.
Usage: generate_lwip_prefix.py <output header> <lwIP source dir> [ww_lwip archive ...]
Run it on an unprefixed ww_lwip archive after an lwIP upgrade; the build's lwIP prefix
contract names any symbol the header is missing.
"""
import re
import subprocess
import sys
from pathlib import Path

output = Path(sys.argv[1])
source = Path(sys.argv[2])
symbols = set()
for archive in sys.argv[3:]:
    text = subprocess.check_output(["nm", "-g", "--defined-only", archive], text=True)
    for line in text.splitlines():
        fields = line.split()
        if len(fields) >= 3:
            symbol = fields[-1].removeprefix("_").removeprefix("srpww_")
            if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", symbol):
                symbols.add(symbol)
if output.exists():
    for line in output.read_text().splitlines():
        match = re.fullmatch(r"#define ([A-Za-z_][A-Za-z0-9_]*) srpww_\1", line)
        if match:
            symbols.add(match.group(1))

# lwIP lets a port replace some functions with macros and tests those names with #ifndef
# or defined(); an object-like rename would skip their declarations, so they keep their names.
guarded = set()
for path in list(source.rglob("*.[ch]")) + list(output.parent.glob("lwipopts*.h")):
    text = path.read_text(errors="replace")
    guarded.update(re.findall(r"#\s*if(?:n)?def\s+([a-z_][a-z0-9_]*)", text))
    guarded.update(re.findall(r"defined\s*\(?\s*([a-z_][a-z0-9_]*)", text))
kept = sorted(symbols & guarded)
symbols -= guarded
# WaterWall's own engine glue is already in its ww* namespace and is declared before lwipopts.h.
symbols = {symbol for symbol in symbols if not symbol.startswith("ww")}

with output.open("w") as handle:
    handle.write("// Generated by WaterWall/generate_lwip_prefix.py; do not edit.\n")
    handle.write("// kept: " + " ".join(kept) + "\n")
    handle.write("#ifndef SRP_WW_LWIP_PREFIX_H\n#define SRP_WW_LWIP_PREFIX_H\n")
    for symbol in sorted(symbols):
        handle.write(f"#define {symbol} srpww_{symbol}\n")
    handle.write("#endif\n")
print(f"{len(symbols)} lwIP symbols renamed, {len(kept)} kept: {' '.join(kept)}")
